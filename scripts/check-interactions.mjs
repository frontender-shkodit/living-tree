import { chromium, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const page = await browser.newPage({ viewport: { width: 360, height: 800 } });
const checks = [];
let requests = [];
let mode = 'missing';
let release;
await page.route('**/api/orders', async route => {
  requests.push(route.request().postDataJSON());
  if (mode === 'pending') await new Promise(resolve => { release = resolve; });
  if (mode === 'network') return route.abort();
  if (mode === 'malformed') return route.fulfill({ status: 200, contentType: 'text/html', body: '<html>Unavailable</html>' });
  await route.fulfill({ status: mode === 'missing' ? 404 : mode === 'server' ? 500 : 200, contentType: 'application/json', body: JSON.stringify({ accepted: mode === 'success' || mode === 'pending' }) });
});
try {
  await page.goto('http://127.0.0.1:5173');
  const productButton = page.locator('.product-card button').nth(2);
  await productButton.click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toContainText('15–20 см (2 кроны)');
  await expect(dialog.getByPlaceholder('Имя*')).toBeFocused();
  await expect(page.locator('body')).toHaveCSS('overflow', 'hidden');
  await page.keyboard.press('Shift+Tab');
  await expect(dialog.getByRole('button', { name: 'Закрыть окно заказа' })).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(dialog.getByRole('button', { name: 'Заказать дерево', exact: true })).toBeFocused();
  checks.push('Selected product, initial focus, focus trap, scroll lock');
  await dialog.getByRole('button', { name: 'Заказать дерево', exact: true }).click();
  await expect(dialog.getByPlaceholder('Имя*')).toHaveAttribute('aria-invalid', 'true');
  await expect(dialog.getByPlaceholder('Телефон*')).toHaveAttribute('aria-invalid', 'true');
  expect(requests.length).toBe(0);
  await dialog.getByPlaceholder('Имя*').fill('Анна');
  await dialog.getByPlaceholder('Телефон*').fill('123');
  await dialog.getByRole('button', { name: 'Заказать дерево', exact: true }).click();
  expect(requests.length).toBe(0);
  checks.push('Empty fields and invalid phone blocked before request');
  await dialog.getByPlaceholder('Телефон*').fill('8 (989) 522-67-79');
  await dialog.getByPlaceholder('Комментарий').fill('Подарок');
  await dialog.getByRole('button', { name: 'Заказать дерево', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('не подключена');
  expect(requests[0]).toMatchObject({ phone: '+79895226779', product: { id: 'double-small' }, comment: 'Подарок' });
  await expect(dialog.getByPlaceholder('Имя*')).toHaveValue('Анна');
  checks.push('Phone normalization, product payload, unconnected endpoint and data preservation');
  for (const failure of ['network', 'server', 'unconfirmed', 'malformed']) {
    mode = failure;
    await dialog.getByRole('button', { name: 'Заказать дерево', exact: true }).click();
    await expect(dialog.getByRole('alert')).toBeVisible();
    await expect(dialog.getByRole('button', { name: 'Заказать дерево', exact: true })).toBeEnabled();
    await expect(dialog).not.toContainText('Спасибо за заказ');
  }
  checks.push('Network failure, server error and unconfirmed response never show success');
  mode = 'pending';
  const before = requests.length;
  await dialog.getByRole('button', { name: 'Заказать дерево', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Отправляем…' })).toBeDisabled();
  await dialog.locator('form').evaluate(form => { form.requestSubmit(); form.requestSubmit(); });
  expect(requests.length).toBe(before + 1);
  release();
  await expect(dialog).toContainText('Спасибо за заказ');
  await dialog.getByRole('button', { name: 'Закрыть', exact: true }).click();
  await expect(productButton).toBeFocused();
  checks.push('Pending state, duplicate submit prevention, confirmed success and focus return');
  await page.locator('.hero').getByRole('button', { name: 'Заказать дерево' }).click();
  await expect(dialog).not.toContainText('Вы выбрали');
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  checks.push('Hero opens general form; Escape closes dialog');
  mode = 'success';
  const inline = page.locator('#order');
  await inline.getByPlaceholder('Имя*').fill('Мария');
  await inline.getByPlaceholder('Телефон*').fill('9895226779');
  await inline.getByRole('button', { name: 'Заказать дерево' }).click();
  await expect(dialog).toContainText('Спасибо за заказ');
  await page.keyboard.press('Escape');
  checks.push('Inline form opens confirmation after accepted response');
  const region = page.getByRole('region', { name: /Отзывы:/ });
  await region.focus();
  const author = await region.locator('.review-author').first().textContent();
  await page.keyboard.press('ArrowRight');
  await expect(region.locator('.review-author').first()).not.toHaveText(author);
  await page.keyboard.press('ArrowLeft');
  await expect(region.locator('.review-author').first()).toHaveText(author);
  await region.evaluate(element => {
    const start = new Touch({ identifier: 1, target: element, clientX: 250, clientY: 100 });
    const end = new Touch({ identifier: 1, target: element, clientX: 100, clientY: 105 });
    element.dispatchEvent(new TouchEvent('touchstart', { bubbles: true, touches: [start] }));
    element.dispatchEvent(new TouchEvent('touchend', { bubbles: true, changedTouches: [end] }));
  });
  await expect(region.locator('.review-author').first()).not.toHaveText(author);
  checks.push('Reviews support arrows and horizontal swipe');
  for (const width of [320, 360, 480, 768, 1920]) {
    await page.setViewportSize({ width, height: 600 });
    await page.locator('.hero').getByRole('button', { name: 'Заказать дерево' }).click();
    const bounds = await dialog.boundingBox();
    expect(bounds.x).toBeGreaterThanOrEqual(0);
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width);
    await dialog.screenshot({ path: `docs/screenshots/order-dialog-${width}.png` });
    await page.keyboard.press('Escape');
  }
  checks.push('Dialog stays inside viewport at five widths');
  await writeFile('docs/interaction-check.json', JSON.stringify({ checks, backend: 'Mocked in browser; no real orders sent' }, null, 2));
  console.log(JSON.stringify({ checks: checks.length, result: 'passed' }));
} finally { await browser.close(); }
